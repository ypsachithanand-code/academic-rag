from typing import Any, Dict, List, Optional

from qdrant_client import QdrantClient
from qdrant_client.http import models

from app.core.config import settings
from app.core.logging import logger


class QdrantService:
    """Service wrapper for interacting with the local Qdrant vector database."""

    def __init__(
        self,
        url: str = settings.QDRANT_URL,
        timeout: float = settings.QDRANT_TIMEOUT,
        collection_name: str = settings.QDRANT_COLLECTION,
    ):
        self.url = url
        self.timeout = timeout
        self.collection_name = collection_name
        self._client: Optional[QdrantClient] = None

    @property
    def client(self) -> QdrantClient:
        """Return a cached Qdrant client instance."""
        if self._client is None:
            self._client = QdrantClient(
                url=self.url,
                timeout=self.timeout,
            )
        return self._client

    def check_health(self) -> bool:
        """Return True when Qdrant is reachable."""
        try:
            self.client.get_collections()
            return True
        except Exception as exc:
            logger.warning(f"Qdrant health check failed: {exc}")
            return False

    def collection_exists(
        self,
        collection_name: Optional[str] = None,
    ) -> bool:
        """Check whether a Qdrant collection exists."""
        name = collection_name or self.collection_name
        return self.client.collection_exists(collection_name=name)

    def ensure_collection(
        self,
        vector_size: int,
        collection_name: Optional[str] = None,
    ) -> None:
        """
        Create the collection if it does not already exist.

        The collection uses cosine distance because BGE-M3 embeddings
        generated by the embedding service are L2-normalized.
        """
        name = collection_name or self.collection_name

        if self.collection_exists(name):
            logger.info(
                f"Qdrant collection already exists: {name}"
            )
            return

        logger.info(
            f"Creating Qdrant collection '{name}' "
            f"with vector dimension {vector_size}."
        )

        self.client.create_collection(
            collection_name=name,
            vectors_config=models.VectorParams(
                size=vector_size,
                distance=models.Distance.COSINE,
            ),
        )

        logger.info(
            f"Qdrant collection created successfully: {name}"
        )

    def get_collection_info(
        self,
        collection_name: Optional[str] = None,
    ) -> Dict[str, Any]:
        """Return basic information about a Qdrant collection."""
        name = collection_name or self.collection_name

        info = self.client.get_collection(collection_name=name)

        return {
            "collection_name": name,
            "status": str(info.status),
            "vectors_count": info.points_count,
            "points_count": info.points_count,
            "vector_size": getattr(info.config.params.vectors, "size", None),
            "distance": str(getattr(info.config.params.vectors, "distance", "")),
        }

    def count_points(
        self,
        collection_name: Optional[str] = None,
    ) -> int:
        """Return the number of points currently stored."""
        name = collection_name or self.collection_name

        result = self.client.count(
            collection_name=name,
            exact=True,
        )

        return result.count

    def upsert_points(
        self,
        points: List[models.PointStruct],
        batch_size: int = settings.QDRANT_UPSERT_BATCH_SIZE,
        collection_name: Optional[str] = None,
    ) -> None:
        """Upsert Qdrant points in configurable batches."""
        if not points:
            return

        name = collection_name or self.collection_name

        for start in range(0, len(points), batch_size):
            batch = points[start : start + batch_size]

            self.client.upsert(
                collection_name=name,
                points=batch,
                wait=True,
            )

            logger.debug(
                f"Upserted Qdrant batch "
                f"{start + 1}-{start + len(batch)} "
                f"of {len(points)} points."
            )

    def search(
        self,
        query_vector: List[float],
        top_k: int = settings.TOP_K,
        document_id: Optional[str] = None,
        document_ids: Optional[List[str]] = None,
        collection_name: Optional[str] = None,
    ) -> List[Any]:
        """Perform semantic vector search with an optional single or multi-document filter."""
        name = collection_name or self.collection_name

        query_filter = None

        if document_ids:
            query_filter = models.Filter(
                must=[
                    models.FieldCondition(
                        key="document_id",
                        match=models.MatchAny(any=document_ids),
                    )
                ]
            )
        elif document_id:
            query_filter = models.Filter(
                must=[
                    models.FieldCondition(
                        key="document_id",
                        match=models.MatchValue(value=document_id),
                    )
                ]
            )


        return self.client.search(
            collection_name=name,
            query_vector=query_vector,
            query_filter=query_filter,
            limit=top_k,
            with_payload=True,
        )

    def delete_document_points(
        self,
        document_id: str,
        collection_name: Optional[str] = None,
    ) -> None:
        """Delete every Qdrant point belonging to a document."""
        name = collection_name or self.collection_name

        self.client.delete(
            collection_name=name,
            points_selector=models.FilterSelector(
                filter=models.Filter(
                    must=[
                        models.FieldCondition(
                            key="document_id",
                            match=models.MatchValue(value=document_id),
                        )
                    ]
                )
            ),
            wait=True,
        )

        logger.info(
            f"Deleted Qdrant points for document_id={document_id}"
        )


qdrant_service = QdrantService()
